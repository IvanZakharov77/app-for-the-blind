FREE_TAIL = ("напиши", "напиши сообщение", "отправь сообщение", "ответь", "запиши заметку", "найди в интернете", "найди на ютубе", "включи песню", "включи фильм",
             "найди фильм", "найди музыку", "открой сайт", "читай книгу", "мой город", "меня зовут")

_APOSTROPHES = str.maketrans({"’": "'", "ʼ": "'", "`": "'", "‘": "'"})


def _tokens(text: str) -> List[str]:
    return text.lower().translate(_APOSTROPHES).split()


_PHRASE_LIST: List[Tuple[List[str], str]] = sorted(((key.split(), value) for key, value in PHRASES.items()),
                                                   key=lambda item: -len(item[0]))


def to_russian(text: str) -> str:
    """The Russian command for a Ukrainian phrase; names and the person's own text are kept."""
    words = _tokens(text)
    said: List[str] = []
    index = 0
    while index < len(words):
        for phrase, value in _PHRASE_LIST:
            if words[index:index + len(phrase)] == phrase:
                said.append(value)
                index += len(phrase)
                break
        else:
            said.append(WORDS.get(words[index], words[index]))
            index += 1
        head = " ".join(said)
        following = WORDS.get(words[index], "") if index < len(words) else ""
        for start in FREE_TAIL:
            if following in ("сообщение", "заметку", "на", "в") and start in ("напиши", "ответь", "запиши"):
                continue  # «напиши повідомлення …», «відповідай на дзвінок»: the command goes on
