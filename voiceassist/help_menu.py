# Strong: the person clearly asks for help («какие команды по …»), so an unknown topic gets the topic list.
_STRONG = (r"(?:(?:какие|какие у тебя|какие есть|какие ты знаешь|какие там) (?:есть )?команды|команды|команда|"
           r"список команд|помощь|справка|подсказка|подскажи команды|подскажи|категория|категорию|категории|"
           r"раздел|тема|тему)")
# Weak: «что ты умеешь по …», «как пользоваться …», «расскажи про …» answer with help only when a topic is
# named, otherwise the phrase goes on as usual («расскажи про космос» to Gemini, «что ты знаешь обо мне»).
_WEAK = (r"(?:(?:что|чего|чо|што) (?:ты |вы )?(?:умеешь|умеете|можешь|можете|знаешь|можно)(?: делать| сказать)?|"
         r"как (?:пользоваться|работать|управлять)|расскажи (?:про|о|об)|что можно (?:делать )?(?:с|со|в))")
_POLITE = r"(?:(?:а|ну|вега|скажи|напомни мне|ещё|еще) )*"
_PREPOSITION = r"(?:(?:по|про|для|о|об|с|со|в|на|у) )?"
STRONG_PHRASE = re.compile(_POLITE + _STRONG + " " + _PREPOSITION + r"(.+)")
WEAK_PHRASE = re.compile(_POLITE + _WEAK + " " + _PREPOSITION + r"(.+)")
# «телеграм какие команды», «по напоминаниям что ты умеешь»
AFTER_PHRASE = re.compile(r"(?:по |про )?(.+?) (?:какие (?:есть )?команды|что ты умеешь|что ты можешь|что можно)")
CATEGORY_PHRASE = STRONG_PHRASE  # older name


def topic_names() -> Tuple[str, ...]:
    return tuple(name for name, _keys, _forms, _commands in CATEGORIES)


def categories_message(context: Sequence[str] = ()) -> Tuple[str, Tuple[str, ...]]:
    names = topic_names()
    head = ""
    if context:
        head = "Сейчас можно сказать: {}. ".format(", ".join("«{}»".format(item) for item in context))
    return (head + "Я умею многое. Спросите про любую тему, например: Вега, какие команды по телеграму. Темы такие: "
            + "; ".join(names) + ". Любую команду можно сказать и сразу."), names


def _plain(text: str) -> str:
    return text.casefold().replace("ё", "е")


def _scores(spoken: str):
    text = " " + _plain(spoken) + " "
    words = text.split()
    scores = []
    for index, (_name, keys, _forms, _commands) in enumerate(CATEGORIES):
        score = 0
        for key in keys:
            key = _plain(key)
            if " " in key:  # a whole phrase: every word of it starts a word of the question, in order
                parts = key.split()
                if re.search(r"\b" + r"\w*\s+(?:\w+\s+)?".join(map(re.escape, parts)), text):
                    score += 3
            elif any(word.startswith(key) for word in words):
                score += 1
        scores.append(score)
    return scores


def _fuzzy(spoken: str) -> Optional[int]:
    """Poor diction: «тилиграм», «напаминания». The word start is compared with every stem by sound."""
    best, best_index = 0.0, None
    for word in _plain(spoken).split():
        if len(word) < 4:
            continue
        for index, (_name, keys, _forms, _commands) in enumerate(CATEGORIES):
            for key in keys:
                key = _plain(key)
                if " " in key or len(key) < 5:
                    continue
                ratio = max(difflib.SequenceMatcher(None, word[:size], key).ratio() for size in (len(key), len(key) + 1))
                if ratio > best:
                    best, best_index = ratio, index
    return best_index if best >= 0.75 else None


def find_category(spoken: str) -> Optional[int]:
    """Index of the topic named by «телеграм», «по запискам», «три»; None when nothing fits or two fit equally."""
    number = parse_index(spoken)
    if number is not None and not _plain(spoken).startswith("по "):
        if len(spoken.split()) <= 3 and 0 < number <= len(CATEGORIES):
            return number - 1
    scores = _scores(spoken)
    top = max(scores)
    if top == 0:
        return _fuzzy(spoken)
    best = [index for index, score in enumerate(scores) if score == top]
    return best[0] if len(best) == 1 else None


def topic_question(command: str) -> Optional[Tuple[str, bool]]:
    """(topic words, strong) of a help question: «какие команды по телеграму» gives («телеграму», True).
    None when the phrase is not a help question."""
    found = STRONG_PHRASE.fullmatch(command)
    if found:
        return found.group(1).strip(), True
    for pattern in (WEAK_PHRASE, AFTER_PHRASE):
        found = pattern.fullmatch(command)
        if found:
            return found.group(1).strip(), False
    return None


def category_message(index: int) -> Tuple[str, Tuple[str, ...]]:
    name, _keys, _forms, commands = CATEGORIES[index]
    return ("{}. Сначала скажите: Вега, а потом команду. Например: {}.".format(name[0].upper() + name[1:], "; ".join(commands)),
            commands)


def grammar_phrases() -> Tuple[str, ...]:
    """Help questions for the command-only recognizer, so «какие команды по телеграму» is heard whole."""
    phrases = []
    for index, (name, _keys, forms, _commands) in enumerate(CATEGORIES):
        for form in forms:
            phrases.extend(("какие команды по " + form, "команды по " + form, "что ты умеешь по " + form,
                            "помощь по " + form))
        phrases.extend(("категория " + name, "расскажи про " + name))
    return tuple(_plain(phrase).replace("gemini", "гемини") for phrase in phrases)
