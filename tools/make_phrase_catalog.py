"""Rebuild voiceassist/phrase_catalog.py: every fixed command phrase the routers compare against.

Vega uses the catalog to recover a command Vosk heard slightly wrong («что на флэшке»).
Run after adding fixed phrases: python tools/make_phrase_catalog.py
"""

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ("core.py", "file_routes.py", "browser_routes.py")
TARGET = ROOT / "voiceassist" / "phrase_catalog.py"


def harvest():
    found = set()
    for name in SOURCES:
        tree = ast.parse((ROOT / "voiceassist" / name).read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            values = []
            if isinstance(node, ast.Compare) and isinstance(node.left, ast.Name) and node.left.id == "command":
                for comparator in node.comparators:
                    values += comparator.elts if isinstance(comparator, (ast.Tuple, ast.List, ast.Set)) else [comparator]
            elif isinstance(node, ast.Dict):
                values = [key for key in node.keys if key is not None]
            for value in values:
                if isinstance(value, ast.Constant) and isinstance(value.value, str):
                    found.add(value.value)
    # Only whole commands: two words or more, Russian, never a confirmation phrase.
    return sorted(phrase for phrase in found
                  if re.fullmatch(r"[а-я]+(?: [а-я]+)+", phrase) and not phrase.startswith("подтверждаю"))


def render(phrases):
    lines = ['"""Generated by tools/make_phrase_catalog.py, do not edit by hand."""', "", "PHRASES = ("]
    lines += ['    "{}",'.format(phrase) for phrase in phrases]
    lines.append(")")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(harvest()), encoding="utf-8")
    print("phrases:", len(harvest()))
